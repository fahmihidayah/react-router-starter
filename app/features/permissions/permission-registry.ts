function permission(
  key: PermissionKey,
  resource: string,
  action: string,
  name: string,
): PermissionDefinition {
  return {
    key,
    resource,
    action,
    name,
    description: `Allows the role to ${action} ${resource.replaceAll('-', ' ')}`,
  }
}
